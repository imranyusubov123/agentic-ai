import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import assert from 'node:assert/strict';
const context={};runInNewContext(readFileSync(new URL('../src/main/resources/static/blog/text-editor.js',import.meta.url),'utf8'),context);
const {format}=context.BlogTextEditor;
assert.equal(format('Hello world',6,11,'bold').value,'Hello **world**');
assert.equal(format('Hello',0,5,'italic').value,'*Hello*');
assert.equal(format('one\ntwo\nthree',0,8,'bullet').value,'- one\n- two\nthree');
assert.equal(format('one\ntwo',0,7,'numbered').value,'1. one\n2. two');
assert.equal(format('# Intro',0,7,'h2').value,'## Intro');
assert.equal(format('alpha\nbeta',6,6,'h3').value,'alpha\n### beta');
assert.equal(format('say hi',4,6,'inline-code').value,'say `hi`');
const link=format('Docs',0,4,'link');assert.equal(link.value,'[Docs](https://example.com)');assert.equal(link.value.slice(link.start,link.end),'https://example.com');
assert.equal(format('',0,0,'quote').value,'> ');
assert.equal(format('int i = 1;',0,10,'code').value,'```java\nint i = 1;\n```');
assert.ok(format('',0,0,'table').value.includes('| --- | --- |'));
assert.equal(format('BeforeAfter',6,6,'divider').value,'Before\n\n---\n\nAfter');
assert.throws(()=>format('a'.repeat(200000),0,1,'bold'),/limit/);
console.log('13 formatting checks passed.');
